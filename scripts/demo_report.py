"""Capture the deterministic scan, paper fills, and settlement in a fresh database."""

import argparse
import asyncio
import json
import subprocess
import sys
from collections import Counter
from decimal import Decimal
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from app.config import Settings
from app.connectors.mock import demo_batch
from app.database.session import Database
from app.schemas.domain import now
from app.services.market_data import ResearchRuntime
from app.services.paper_trading import PaperExecutionProvider

ROOT = Path(__file__).resolve().parents[1]


async def capture(database_path: Path) -> dict[str, Any]:
    # Explicit defaults override shell/.env settings so the evidence is reproducible.
    defaults = {name: field.get_default() for name, field in Settings.model_fields.items()}
    defaults.update(
        database_url=f"sqlite+aiosqlite:///{database_path}",
        mapping_file=str(ROOT / "docs/contract-mappings.json"),
    )
    settings = Settings(_env_file=None, **defaults)
    rt = ResearchRuntime(settings, Database(settings.database_url), connector_factory=lambda: [])
    await rt.start()
    try:
        await rt.ingest(demo_batch(tick=0))
        opportunities = rt.current_opportunities()
        executable = [o for o in opportunities if o.status == "executable"]
        trades = []
        async with rt.lock:
            for op in executable:
                trades.append(await rt.paper.execute_order(op, rt.books))
            capital_after_fills = str(rt.paper.free_capital)
            try:
                await rt.paper.execute_order(executable[0], rt.books)
            except ValueError as exc:
                duplicate_result = str(exc)
            else:
                raise AssertionError("Duplicate execution was incorrectly accepted")
            settled = [
                await rt.paper.settle(t["id"], {key: "YES" for key in t["market_keys"]})
                for t in trades
            ]
        restored = PaperExecutionProvider(rt.db, rt.engine)
        await restored.restore()
        assert restored.realized_pnl == rt.paper.realized_pnl
        assert restored.free_capital == rt.paper.free_capital
        assert len(restored.trades) == len(trades)
        economics = [
            "requested_size",
            "paper_capital",
            "max_capital_per_opportunity",
            "max_capital_per_market",
            "fee_bps",
            "kalshi_fee_coefficient",
            "network_cost",
            "latency_buffer_bps",
            "min_net_edge",
            "min_liquidity",
            "max_slippage",
        ]
        config = settings.model_dump(mode="json")
        return {
            "captured_at": now().isoformat(),
            "mode": "mock",
            "fixture_tick": 0,
            "scope": "Deterministic synthetic books; real quant and paper-ledger code; isolated SQLite database; no venue orders",
            "settings": {k: config[k] for k in economics},
            "summary": {
                "markets": len({s.key for s in rt.books.values()}),
                "snapshots": len(rt.books),
                "checks": len(opportunities),
                "classifications": dict(Counter(o.status for o in opportunities)),
                "paired_trades": len(settled),
                "filled_orders": sum(len(t["orders"]) for t in settled),
                "starting_capital": str(settings.paper_capital),
                "capital_after_fills": capital_after_fills,
                "settled_simulation_pnl": str(rt.paper.realized_pnl),
                "ending_capital": str(rt.paper.free_capital),
                "duplicate_execution": duplicate_result,
                "ledger_restore": "passed",
            },
            "opportunities": [o.model_dump(mode="json") for o in opportunities],
            "trades": settled,
        }
    finally:
        await rt.stop()


def render(report: dict[str, Any]) -> str:
    def percent(value: str | None) -> str:
        return "—" if value is None else f"{Decimal(value) * 100:.4f}%"

    def usd(value: str | None) -> str:
        return "—" if value is None else f"${Decimal(value):.6f}"

    summary = report["summary"]
    lines = [
        "# Recorded demo run",
        "",
        f"Captured **{report['captured_at']}** using synthetic fixture tick 0.",
        "",
        "This report is generated by `uv run python scripts/demo_report.py` (`make demo-report`). "
        "It exercises the application quant services and paper ledger in a fresh temporary SQLite database. "
        "No running server, credentials, real funds, or external network are needed.",
        "",
        f"Engine source revision: `{report['engine_source_revision']}`. "
        "Timestamps and IDs vary on rerun; economic results use explicit default configuration.",
        "",
        "## Scan results",
        "",
        f"**{summary['markets']} venue markets · {summary['snapshots']} snapshots · {summary['checks']} checks · "
        f"{summary['classifications']['executable']} executable · {summary['classifications']['theoretical']} theoretical · "
        f"{summary['classifications']['rejected']} rejected**",
        "",
        "| Contract(s) | Gross edge | Net edge | Available shares | Expected P&L | Status / reason |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for op in report["opportunities"]:
        lines.append(
            f"| {' + '.join(op['market_keys'])} | {percent(op['gross_edge'])} | {percent(op['net_edge'])} | "
            f"{op['available_size']} | {usd(op['expected_profit'])} | {op['status']}: {op['rejection_reason'] or 'all configured checks pass'} |"
        )
    lines += [
        "",
        "Edges are dollars per $1 paired payout, displayed as percentages; they are not annualized returns. "
        "An incomplete pair has no net-edge or profit estimate. Available shares describe paired depth at the assessed size, not an execution approval.",
        "",
        "## Filled and settled paper trades",
        "",
        "Both executable pairs were purchased, then every venue contract was supplied a synthetic YES resolution.",
        "",
        "| Strategy | Paired shares | Modeled outlay | Simulated settlement P&L |",
        "| --- | ---: | ---: | ---: |",
    ]
    for trade in report["trades"]:
        lines.append(
            f"| {trade['strategy_type']} | {trade['quantity']} | {usd(trade['total_cost'])} | {usd(trade['realized_pnl'])} |"
        )
    lines += [
        "",
        f"- Starting paper capital: **{usd(summary['starting_capital'])}**.",
        f"- Free capital after both fills: **{usd(summary['capital_after_fills'])}**.",
        f"- Ending paper capital after settlement: **{usd(summary['ending_capital'])}**.",
        f"- Combined simulated settlement P&L: **{usd(summary['settled_simulation_pnl'])}**.",
        f"- Duplicate-order attempt: rejected with `{summary['duplicate_execution']}`.",
        "- Reloaded the persisted ledger and verified both trade count and capital/P&L: **passed**.",
        "",
        "The Ethereum pair walks beyond the 90-share best ask on each leg. The CPI cross-venue pair uses an explicitly validated synthetic mapping and the Kalshi-like fee model. "
        "The Bitcoin edge is removed by fees; GDP lacks enough depth for the requested pair.",
        "",
        "## Evidence and assumptions",
        "",
        "[Raw JSON](demo-run.json) includes every normalized input book, opportunity estimate, filled level, fee, resolution, and ledger result. "
        "Default requested size is 100 paired shares; the $100 opportunity budget may reduce it. "
        "Polymarket-like fees are 20 bps of notional; Kalshi-like fees use coefficient 0.07 with cent rounding. "
        "Each Polymarket leg adds $0.02 network cost, and each leg reserves 10 bps of payout for latency.",
        "",
        "**This is a functional demonstration, not a backtest or investment-performance record.** "
        "Synthetic inefficiencies and matching resolutions are deliberately supplied. Real legs are non-atomic, "
        "fees differ by market, and cross-venue resolution divergence can produce losses. "
        "See [execution assumptions](EXECUTION_MODEL.md) and [validation scope](VALIDATION.md).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "docs")
    args = parser.parse_args()
    with TemporaryDirectory(prefix="arbitrage-demo-") as directory:
        report = asyncio.run(capture(Path(directory) / "demo.db"))
    report["engine_source_revision"] = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
    ).strip()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "demo-run.json").write_text(json.dumps(report, indent=2) + "\n")
    (args.output_dir / "DEMO_RESULTS.md").write_text(render(report))
    print(json.dumps(report["summary"], indent=2))


if __name__ == "__main__":
    main()
